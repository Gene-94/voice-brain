"""Stats generator: collect day's inputs -> Gemma extracts -> deterministic numbers
are precomputed by insights.py -> validated JSON written to Stats/YYYY-MM-DD.json.

Same code path for voice trigger, `voice-brain generate-stats`, and the nightly timer.
"""

from __future__ import annotations

import json
from datetime import date as Date, datetime, timedelta
from pathlib import Path

from . import insights
from .creative_output import CreativeOutput
from .prompts import PROMPT_VERSIONS, stats_v1
from .stats_schema import validate_stats
from .vault import parse_frontmatter

MD_SUMMARY = """# Daily Stats — {pretty_date}

**Readiness:** {readiness}/100 | **Wellbeing:** {wellbeing}/10 | **Creative Output:** {creativity}/100

{categories}

## Top Recommendation
1. **{rec}**

*Generated by Voice Brain (gemma via Ollama) — {generated_at}*
"""


class StatsGenerator:
    def __init__(self, cfg, vault, llm, ledger):
        self.cfg = cfg
        self.vault = vault
        self.llm = llm
        self.ledger = ledger
        self.creative = CreativeOutput(cfg, vault, llm)

    # ------------------------------------------------------------------ input collection

    def collect_inputs(self, day: Date) -> dict:
        dream_notes = self.vault.dream_files(day)
        journal_path = self.vault.journal_path(day)
        journal_text = journal_path.read_text() if journal_path.exists() else ""
        _, journal_body = parse_frontmatter(journal_text)

        blocks: list[str] = []
        for note in dream_notes:
            blocks.append(f"[{note.rel}]\n{note.body[:800].strip()}")
        if journal_body.strip():
            blocks.append(f"[{journal_path.relative_to(self.vault.root).as_posix()}]\n"
                          f"{journal_body[:4000].strip()}")
        entries_ctx = "\n\n".join(blocks) or "(no dream or journal entries today)"

        history: list[dict] = []
        n_days = int(self.cfg.get("stats.history_days", 7))
        for i in range(1, n_days + 1):
            p = self.vault.stats_path(day - timedelta(days=i))
            if p.exists():
                try:
                    history.append(json.loads(p.read_text()))
                except json.JSONDecodeError:
                    continue

        creative_block = self.creative.collect(day)

        journal_days = set()
        journal_dir = self.vault.root / self.cfg.folder("journal")
        if journal_dir.exists():
            for p in journal_dir.glob("*.md"):
                try:
                    journal_days.add(Date.fromisoformat(p.stem))
                except ValueError:
                    pass

        precomputed = insights.precompute_block(
            today=None, history=history,
            journal_words=len(journal_body.split()),
            creative_words=int(creative_block.get("total_words_produced", 0)),
            journal_days=journal_days, today_date=day,
            min_days=int(self.cfg.get("insights.min_days_for_correlation", 5)),
        )
        return {
            "entries_ctx": entries_ctx,
            "creative_block": json.dumps(creative_block, ensure_ascii=False, indent=1),
            "history_ctx": json.dumps(
                [{k: h.get(k) for k in ("date", "derived", "sleep", "mood", "energy")}
                 for h in history], ensure_ascii=False, default=str)[:6000] or "(no history)",
            "precomputed": json.dumps(precomputed, ensure_ascii=False, indent=1),
        }

    # ------------------------------------------------------------------ generation

    def generate(self, day: Date | None = None, now: datetime | None = None,
                  write_markdown: bool | None = None) -> Path:
        day = day or Date.today()
        now = now or datetime.now()
        inputs = self.collect_inputs(day)

        prompt = stats_v1(
            day=day.isoformat(),
            entries_ctx=inputs["entries_ctx"],
            creative_block=inputs["creative_block"],
            history_ctx=inputs["history_ctx"],
            precomputed=inputs["precomputed"],
        )
        doc = self.llm.generate(prompt, lane="deep", json_mode=True,
                                validator=validate_stats)

        # Authoritative fields are set by code, not the LLM:
        doc["date"] = day.isoformat()
        doc["generated_at"] = now.isoformat(timespec="seconds")
        doc["schema_version"] = "1.0.0"
        doc["generated_by"] = {
            "model": self.llm.lane("deep").model,
            "prompt_version": PROMPT_VERSIONS["stats_v1"],
            "temperature": self.cfg.get("llm.temperature_deep", 0.3),
        }

        # merge precomputed correlations back (LLM may echo them imperfectly)
        pre = json.loads(inputs["precomputed"])
        if isinstance(doc.get("insights"), dict):
            doc["insights"]["correlations"] = pre["correlations"]
        if isinstance(doc.get("derived"), dict):
            doc["derived"]["trending"] = pre["trend"]["trending"]

        out = self.vault.stats_path(day, "json")
        self.vault.write_atomic(out, json.dumps(doc, ensure_ascii=False, indent=2) + "\n")
        ops = [(out, None)]
        if write_markdown if write_markdown is not None else \
                self.cfg.get("stats.markdown_summary", True):
            md = self.vault.stats_path(day, "md")
            if not md.exists():
                self.vault.write_atomic(md, self.render_summary(doc, day, now))
                ops.append((md, None))
        self.ledger.record(f"stats generated for {day.isoformat()}", ops)
        return out

    def render_summary(self, doc: dict, day: Date, now: datetime) -> str:
        derived = doc.get("derived", {})
        cats = []
        for cat, label in (("sleep", "Sleep"), ("mood", "Mood"), ("energy", "Energy"),
                           ("physical", "Physical"), ("nutrition", "Nutrition")):
            node = doc.get(cat, {})
            cats.append(f"## {label}\n{node.get('notes', '')}")
        recs = derived.get("recommendations") or []
        rec = (recs[0].get("action", "—") + f" (confidence: "
               + str(int(float(recs[0].get("confidence", 0)) * 100)) + "%)") if recs else "—"
        return MD_SUMMARY.format(
            pretty_date=day.strftime("%B %d, %Y"),
            readiness=derived.get("readiness_score", "—"),
            wellbeing=derived.get("wellbeing_index", "—"),
            creativity=doc.get("creative_output", {}).get("creativity_score", "—"),
            categories="\n\n".join(cats),
            rec=rec,
            generated_at=now.strftime("%H:%M"),
        )

    def summarize_for_notification(self, doc: dict) -> str:
        derived = doc.get("derived", {})
        co = doc.get("creative_output", {})
        recs = derived.get("recommendations") or []
        lines = [
            f"Readiness: {derived.get('readiness_score', '—')}/100 | "
            f"Wellbeing: {derived.get('wellbeing_index', '—')}/10",
            f"Notes produced today: {co.get('notes_created_count', 0)} "
            f"({co.get('total_words_produced', 0)} words)",
        ]
        if recs:
            lines.append(f"💡 {recs[0].get('action', '')}")
        return "\n".join(lines)

    # ------------------------------------------------------------------ catch-up

    def catchup(self, now: datetime | None = None) -> list[Path]:
        """Generate any missing stats for the last 3 days (timer Persistent=true parity)."""
        now = now or datetime.now()
        generated: list[Path] = []
        for i in range(1, 4):
            day = now.date() - timedelta(days=i)
            if not self.vault.stats_path(day).exists():
                jp = self.vault.journal_path(day)
                has_input = jp.exists() or self.vault.dream_files(day)
                if has_input:
                    generated.append(self.generate(day, now))
        return generated
