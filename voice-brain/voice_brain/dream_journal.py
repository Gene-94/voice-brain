"""Dream Journal router: \"I had a dream...\" -> one Markdown file per dream."""

from __future__ import annotations

from datetime import date as Date, datetime
from pathlib import Path

from . import templates
from .prompts import PROMPT_VERSIONS, dream_split
from .vault import slugify

TEMPLATE = """---
dream_id: "{{dream_id}}"
dreamt_at: "{{dreamt_at}}"
recorded_at: "{{recorded_at}}"
title: "{{title}}"
vividness: {{vividness}}
lucidity: {{lucidity}}
themes: {{themes}}
emotional_tone: "{{emotional_tone}}"
tags:
  - dream
created_by: voice-brain
model: "{{model}}"
prompt_version: "{{prompt_version}}"
---

# {{title}}

**Dreamt:** {{dreamt_pretty}}
**Vividness:** {{vividness}}/10 | **Lucid:** {{lucid_pretty}}

## Narration

{{narration}}

## Summary

{{summary}}

## Themes & Symbols

{{themes_list}}

## Connections

{{connections}}

---

*Auto-generated by Voice Brain — edit freely, this is your journal.*
"""


def _validate_dreams(doc: object) -> list[str]:
    errors: list[str] = []
    if not isinstance(doc, dict) or "dreams" not in doc:
        return ["top-level object must contain 'dreams' list"]
    dreams = doc["dreams"]
    if not isinstance(dreams, list):
        return ["'dreams' must be a list"]
    for i, d in enumerate(dreams):
        if not isinstance(d, dict):
            errors.append(f"dreams[{i}] must be an object")
            continue
        if not str(d.get("title", "")).strip():
            errors.append(f"dreams[{i}].title is empty")
        if not str(d.get("narration", "")).strip():
            errors.append(f"dreams[{i}].narration is empty")
        v = d.get("vividness")
        if not isinstance(v, (int, float)) or not (1 <= v <= 10):
            errors.append(f"dreams[{i}].vividness must be 1-10")
    return errors


class DreamRouter:
    def __init__(self, cfg, vault, llm, ledger):
        self.cfg = cfg
        self.vault = vault
        self.llm = llm
        self.ledger = ledger

    def handle(self, narration: str, now: datetime | None = None) -> list[str]:
        """Returns list of created file rel paths. Raises LLMError on unrecoverable failure."""
        now = now or datetime.now()
        doc = self.llm.generate(dream_split(narration), lane="quick",
                                json_mode=True, validator=_validate_dreams)
        dreams = doc.get("dreams", [])
        if not dreams:
            return []

        # Cross-day theme connections from the index (no LLM needed — code calculates)
        theme_counts: dict[str, list[str]] = {}
        for note in self.vault.index():
            for theme in (note.frontmatter.get("themes") or []):
                if isinstance(theme, str):
                    theme_counts.setdefault(theme.lower(), []).append(note.path.stem)
        same_day_stems = {n.path.stem for n in self.vault.dream_files(now.date())}

        created: list[str] = []
        ops: list[tuple[Path, str | None]] = []
        for i, dream in enumerate(dreams, start=1):
            rel, path = self._write_dream(dream, now, i, theme_counts, same_day_stems,
                                          narration)
            created.append(rel)
            ops.append((path, None))
        if ops:
            # one action for the whole session: "scratch that" reverts the entire capture
            self.ledger.record(
                f"dream session: {len(ops)} dream{'s' if len(ops) > 1 else ''} captured", ops)
        return created

    def _write_dream(self, dream: dict, now: datetime, seq: int,
                     theme_counts: dict, same_day_stems: set, full_narration: str) -> tuple[str, Path]:
        day: Date = now.date()
        title = str(dream["title"]).strip()
        themes = [str(t) for t in (dream.get("themes") or [])][:6]
        vividness = int(max(1, min(10, float(dream.get("vividness") or 5))))
        lucidity = bool(dream.get("lucidity", False))

        connections: list[str] = []
        for theme in themes:
            for stem in theme_counts.get(theme.lower(), []):
                if stem not in same_day_stems:
                    connections.append(f"- Recurring theme **{theme}**: see also [[{stem}]]")
        connections = list(dict.fromkeys(connections))[:4] or [
            "- First appearance of these themes in your dream journal."]

        content = templates.render(TEMPLATE, {
            "dream_id": f"{day.isoformat()}_{seq:03d}",
            "dreamt_at": now.isoformat(timespec="minutes"),
            "recorded_at": now.isoformat(timespec="minutes"),
            "title": title,
            "vividness": vividness,
            "lucidity": "true" if lucidity else "false",
            "themes": templates.yaml_list(themes),
            "emotional_tone": str(dream.get("emotional_tone", "unclear"))[:120],
            "model": self.llm.lane("quick").model,
            "prompt_version": PROMPT_VERSIONS["dream_split"],
            "dreamt_pretty": now.strftime("%Y-%m-%d %H:%M"),
            "lucid_pretty": "Yes" if lucidity else "No",
            "narration": str(dream.get("narration", full_narration)).strip(),
            "summary": str(dream.get("summary", "")).strip() or "(no summary)",
            "themes_list": "\n".join(f"- **{t}**" for t in themes) or "- (none detected)",
            "connections": "\n".join(connections),
        })

        rel = f"{self.cfg.folder('dream')}/{day.isoformat()}_{slugify(title, max_words=6)}.md"
        path = self.vault.write_note(rel, content)
        return rel, path
