/** Note templates + tiny {{var}} renderer (no dependency). */

import { PROMPT_VERSIONS } from "./prompts";
import { hhmm, serializeFrontmatter, slugify, todayISO } from "./util";

export function render(template: string, vars: Record<string, any>): string {
  return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (_, key) =>
    vars[key] === undefined || vars[key] === null ? "" : String(vars[key]));
}

const DREAM_TEMPLATE = `---
dream_id: "{{dream_id}}"
dreamt_at: "{{dreamt_at}}"
recorded_at: "{{recorded_at}}"
title: "{{title}}"
vividness: {{vividness}}
lucidity: {{lucidity}}
themes:
{{themes}}
emotional_tone: "{{emotional_tone}}"
tags:
  - dream
created_by: voice-brain
model: "{{model}}"
prompt_version: "{{prompt_version}}"
---

# {{title}}

**Dreamt:** {{dreamt_pretty}}
**Vividness:** {{vividness}}/10 | **Lucid:** {{lucid_pretty}}

## Narration

{{narration}}

## Summary

{{summary}}

## Themes & Symbols

{{themes_list}}

## Connections

{{connections}}

---

*Auto-generated by Voice Brain — edit freely, this is your journal.*
`;

export function dreamNote(vars: {
  date: string; seq: number; recordedAt: Date; title: string; vividness: number;
  lucidity: boolean; themes: string[]; emotionalTone: string; narration: string;
  summary: string; connections: string; model: string;
}): string {
  const themesYaml = vars.themes.map((t) => `  - ${t}`).join("\n") || "  - unknown";
  return render(DREAM_TEMPLATE, {
    dream_id: `${vars.date}_${String(vars.seq).padStart(3, "0")}`,
    dreamt_at: vars.recordedAt.toISOString().slice(0, 16),
    recorded_at: vars.recordedAt.toISOString().slice(0, 16),
    title: vars.title.replace(/"/g, "'"),
    vividness: vars.vividness,
    lucidity: vars.lucidity ? "true" : "false",
    themes: themesYaml,
    emotional_tone: vars.emotionalTone.slice(0, 120),
    model: vars.model,
    prompt_version: PROMPT_VERSIONS.dream_split,
    dreamt_pretty: vars.recordedAt.toISOString().replace("T", " ").slice(0, 16),
    lucid_pretty: vars.lucidity ? "Yes" : "No",
    narration: vars.narration,
    summary: vars.summary || "(no summary)",
    themes_list: vars.themes.map((t) => `- **${t}**`).join("\n") || "- (none detected)",
    connections: vars.connections,
  });
}

const DAILY_TEMPLATE = `---
date: "{date}"
created_by: voice-brain
entry_count: 0
prompt_version: "{prompt_version}"
---

# Journal — {pretty_date}
`;

export function dailyJournalNote(date: string, prettyDate: string): string {
  return DAILY_TEMPLATE
    .replaceAll("{date}", date)
    .replaceAll("{pretty_date}", prettyDate)
    .replaceAll("{prompt_version}", PROMPT_VERSIONS.journal_enrich);
}

export function journalEntry(now: Date, heading: string, tags: string[], text: string): string {
  const parts = [`## ${hhmm(now.getTime())} — ${heading}`, "", text.trim()];
  if (tags.length) parts.push("", `<!--vb: ${tags.join(" ")} -->`);
  parts.push("", "---");
  return parts.join("\n");
}

export function inboxNote(now: Date, title: string, tags: string[], content: string,
                          extraFrontmatter: Record<string, any> = {}): string {
  const fm = serializeFrontmatter({
    title,
    tags: tags.length ? tags : ["capture"],
    created_at: now.toISOString().slice(0, 19),
    created_by: "voice-brain",
    ...extraFrontmatter,
  });
  return `${fm}\n# ${title}\n\n${content.trim()}\n`;
}

export function dateStampedName(folder: string, date: string, title: string, ext = "md"): string {
  return `${folder}/${date}_${slugify(title, 6)}.${ext}`;
}
